CREATE DATABASE HABITOS_DB;
USE HABITOS_DB;

CREATE TABLE TBL_HABITO
(
	ID_HABITO BIGINT NOT NULL IDENTITY(1,1) PRIMARY KEY,
	TX_DESCRICAO VARCHAR(500) NOT NULL,
	NR_DIAS_CONSECUTIVOS INT NOT NULL,
	NR_META_DIAS INT NOT NULL,
	FL_CONQUISTA_ALCANCADA BIT NOT NULL DEFAULT 0,

	CONSTRAINT CK_DIAS_CONSECUTIVOS CHECK(NR_DIAS_CONSECUTIVOS >= 0),
	CONSTRAINT CK_META_DIAS CHECK(NR_META_DIAS > 0)
)


